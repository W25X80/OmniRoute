/** Session tables retain the SQLite field representation for lossless offline import. */
export const POSTGRES_SESSION_SCHEMA_STATEMENTS = [
  `CREATE TABLE omniroute.exclusive_connection_leases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_owner_hash text NOT NULL CHECK (lease_owner_hash ~ '^[0-9a-f]{64}$'),
    api_key_id text NOT NULL, provider text NOT NULL, connection_id text NOT NULL,
    generation bigint NOT NULL CHECK (generation > 0),
    state text NOT NULL CHECK (state IN ('ACTIVE','RELEASED','EXPIRED','INVALIDATED')),
    acquired_at text NOT NULL, renewed_at text NOT NULL, expires_at text NOT NULL,
    ended_at text, end_reason text
  )`,
  `CREATE UNIQUE INDEX exclusive_lease_active_owner ON omniroute.exclusive_connection_leases(lease_owner_hash) WHERE state = 'ACTIVE'`,
  `CREATE UNIQUE INDEX exclusive_lease_active_connection ON omniroute.exclusive_connection_leases(connection_id) WHERE state = 'ACTIVE'`,
  `CREATE INDEX exclusive_lease_owner_history ON omniroute.exclusive_connection_leases(lease_owner_hash,generation,id)`,
  `CREATE INDEX exclusive_lease_expiry ON omniroute.exclusive_connection_leases(state,expires_at)`,
  `CREATE TABLE omniroute.context_handoffs (
    id text PRIMARY KEY DEFAULT substr(replace(gen_random_uuid()::text,'-',''),1,16),
    session_id text NOT NULL, combo_name text NOT NULL, from_account text NOT NULL,
    summary text NOT NULL, key_decisions text NOT NULL DEFAULT '[]',
    task_progress text NOT NULL DEFAULT '', active_entities text NOT NULL DEFAULT '[]',
    message_count integer NOT NULL DEFAULT 0, model text NOT NULL DEFAULT '', last_model text,
    warning_threshold_pct double precision NOT NULL DEFAULT 0.85,
    generated_at text NOT NULL, expires_at text NOT NULL, created_at text NOT NULL,
    UNIQUE(session_id,combo_name)
  )`,
  `CREATE INDEX context_handoffs_expiry ON omniroute.context_handoffs(expires_at)`,
  `CREATE TABLE omniroute.session_model_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL, combo_name text NOT NULL, model_str text NOT NULL,
    provider text NOT NULL, connection_id text, used_at text NOT NULL
  )`,
  `CREATE INDEX session_model_history_lookup ON omniroute.session_model_history(session_id,combo_name,used_at DESC,id DESC)`,
  `CREATE INDEX session_model_history_cleanup ON omniroute.session_model_history(used_at)`,
  `CREATE TABLE omniroute.connection_runtime_state (
    connection_id text PRIMARY KEY REFERENCES omniroute.provider_connections(id) ON DELETE CASCADE,
    refresh_circuit_streak integer DEFAULT 0, refresh_circuit_until text, refresh_last_fail_at text,
    warmup_circuit_streak integer DEFAULT 0, warmup_circuit_until text, warmup_last_fail_at text,
    last_warmup_at text, last_warmup_result text, warmup_tokens_used integer DEFAULT 0,
    updated_at text NOT NULL
  )`,
  `CREATE INDEX connection_runtime_warmup_until ON omniroute.connection_runtime_state(warmup_circuit_until) WHERE warmup_circuit_until IS NOT NULL`,
  `CREATE TABLE omniroute.ccr_blocks (
    principal_id text NOT NULL, hash text NOT NULL, content text NOT NULL,
    bytes integer NOT NULL, chars integer NOT NULL, lines integer NOT NULL,
    content_type text NOT NULL DEFAULT 'text/plain', source text NOT NULL DEFAULT 'compression',
    created_at bigint NOT NULL, last_accessed_at bigint NOT NULL, expires_at bigint NOT NULL,
    PRIMARY KEY(principal_id,hash)
  )`,
  `CREATE INDEX ccr_blocks_expires ON omniroute.ccr_blocks(expires_at)`,
  `CREATE TABLE omniroute.cli_access_tokens (
    id text PRIMARY KEY, token_hash text NOT NULL UNIQUE, token_prefix text NOT NULL,
    name text NOT NULL, scope text NOT NULL DEFAULT 'read', created_at text NOT NULL,
    last_used_at text, expires_at text, revoked_at text
  )`,

  `CREATE FUNCTION omniroute.is_retired_lease_provider(provider_id text) RETURNS boolean
   LANGUAGE sql IMMUTABLE AS $$ SELECT
     lower(btrim(provider_id,chr(9) || chr(10) || chr(11) || chr(12) || chr(13) || chr(32) || chr(160) || chr(5760) || chr(8192) || chr(8193) || chr(8194) || chr(8195) || chr(8196) || chr(8197) || chr(8198) || chr(8199) || chr(8200) || chr(8201) || chr(8202) || chr(8232) || chr(8233) || chr(8239) || chr(8287) || chr(12288) || chr(65279))) IN ('felo-web','felo','qwen-web','qw','cgpt-web')
     OR lower(btrim(provider_id,chr(9) || chr(10) || chr(11) || chr(12) || chr(13) || chr(32))) IN ('microsoft-designer-web','msdesigner') $$`,
  `CREATE FUNCTION omniroute.enforce_exclusive_lease_policy() RETURNS trigger
   LANGUAGE plpgsql AS $$ BEGIN
     IF NEW.state='ACTIVE' AND (omniroute.is_retired_lease_provider(NEW.provider)
       OR EXISTS(SELECT 1 FROM omniroute.provider_connections c WHERE c.id=NEW.connection_id
         AND omniroute.is_retired_lease_provider(c.provider))) THEN
       NEW.state := 'INVALIDATED';
       NEW.ended_at := COALESCE(NEW.ended_at,to_char(statement_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'));
       NEW.end_reason := 'CONNECTION_INELIGIBLE';
     END IF;
     RETURN NEW;
   END $$`,
  `CREATE TRIGGER exclusive_lease_retirement_policy BEFORE INSERT OR UPDATE OF provider,connection_id,state
   ON omniroute.exclusive_connection_leases FOR EACH ROW EXECUTE FUNCTION omniroute.enforce_exclusive_lease_policy()`,
  `CREATE FUNCTION omniroute.invalidate_retired_connection_leases() RETURNS trigger
   LANGUAGE plpgsql AS $$ BEGIN
     IF omniroute.is_retired_lease_provider(NEW.provider) THEN
       UPDATE omniroute.exclusive_connection_leases SET state='INVALIDATED',
         ended_at=COALESCE(ended_at,to_char(statement_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
         end_reason='CONNECTION_INELIGIBLE' WHERE connection_id=NEW.id AND state='ACTIVE';
     END IF;
     RETURN NEW;
   END $$`,
  `CREATE TRIGGER provider_retirement_invalidates_leases AFTER INSERT OR UPDATE OF provider
   ON omniroute.provider_connections FOR EACH ROW EXECUTE FUNCTION omniroute.invalidate_retired_connection_leases()`,
] as const;
