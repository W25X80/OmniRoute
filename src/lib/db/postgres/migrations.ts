function checksum(migration: Migration): string {
  return createHash("sha256").update(JSON.stringify(migration)).digest("hex");
}

export class PostgresMigrationError extends Error {
  constructor(readonly reason: "history_mismatch" | "newer_schema") {
    super(
      reason === "history_mismatch"
        ? "PostgreSQL migration history mismatch"
        : "PostgreSQL schema is newer than this application"
    );
    this.name = "PostgresMigrationError";
  }
}

async function applyMigrations(transaction: PostgresTransaction): Promise<void> {
  // Bootstrap and history validation share a transaction lock across all application instances.
  await acquirePostgresLock(transaction, "schema");
  await transaction.query("CREATE SCHEMA IF NOT EXISTS omniroute");
  await transaction.query(`CREATE TABLE IF NOT EXISTS omniroute.schema_migrations (
    version integer PRIMARY KEY, name text NOT NULL, checksum text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  const { rows } = await transaction.query<{ version: number; name: string; checksum: string }>(
    "SELECT version,name,checksum FROM omniroute.schema_migrations ORDER BY version"
  );
  for (let index = 0; index < rows.length; index++) {
    const applied = rows[index];
    const expected = migrations[index];
    if (!expected) throw new PostgresMigrationError("newer_schema");
    if (
      applied.version !== expected.version ||
      applied.name !== expected.name ||
      applied.checksum !== checksum(expected)
    ) {
      throw new PostgresMigrationError("history_mismatch");
    }
  }
  for (const migration of migrations.slice(rows.length)) {
    for (const statement of migration.statements) await transaction.query(statement);
    await transaction.query(
      "INSERT INTO omniroute.schema_migrations(version,name,checksum) VALUES($1,$2,$3)",
      [migration.version, migration.name, checksum(migration)]
    );
  }
}

/** Offline/bootstrap operation. Never runs from a request or mutates SQLite migration history. */
export function migratePostgresSchema(database: PostgresDatabase): Promise<void> {
  return database.transaction(applyMigrations, { operation: "schema.migrate" });
}
