import { getSelectedPostgresDatabase, getSelectedPersistenceIdentity } from "./controlPlaneContext";

/** Opaque cache authority, never a SQL/driver handle at the consumer boundary. */
export function postgresSignatureCacheAuthority(): object | undefined {
  return getSelectedPersistenceIdentity();
}

export function isPostgresSignatureStoreSelected(): boolean {
  return getSelectedPostgresDatabase() !== undefined;
}

export async function readPersistedGeminiThoughtSignatures(keys?: readonly string[]) {
  const database = getSelectedPostgresDatabase();
  if (!database || keys?.length === 0) return new Map<string, string>();
  if (keys && keys.length > 1_000) throw new Error("Gemini signature hydration limit exceeded");
  return database.transaction(async (transaction) => {
    const { rows } = keys
      ? await transaction.query<{ key: string; value: string }>(
          `SELECT key,value FROM omniroute.key_value WHERE namespace='gemini_thought_signatures' AND key=ANY($1::text[])`,
          [[...keys]]
        )
      : await transaction.query<{ key: string; value: string }>(
          `SELECT key,value FROM omniroute.key_value WHERE namespace='gemini_thought_signatures'
         ORDER BY CASE WHEN value IS JSON OBJECT THEN CASE WHEN jsonb_typeof(value::jsonb -> 'createdAt')='number'
         THEN (value::jsonb ->> 'createdAt')::numeric ELSE 0 END ELSE 0 END DESC,key COLLATE "C" ASC LIMIT 2000`
        );
    return new Map(rows.map((row) => [row.key, row.value]));
  });
}

export async function writePersistedGeminiThoughtSignature(
  key: string,
  value: string
): Promise<void> {
  const database = getSelectedPostgresDatabase();
  if (!database) return;
  await database.transaction(async (transaction) => {
    await transaction.query("SELECT pg_advisory_xact_lock(18765,15)");
    await transaction.query(
      `INSERT INTO omniroute.key_value(namespace,key,value)
       VALUES('gemini_thought_signatures',$1,$2)
       ON CONFLICT(namespace,key) DO UPDATE SET value=excluded.value`,
      [key, value]
    );
    // Validate JSON before casting so legacy raw signatures remain readable. The
    // write value is generated by the owner; old raw rows receive the same rewrite
    // on a successful read as the SQLite implementation.
    await transaction.query(
      `DELETE FROM omniroute.key_value WHERE namespace='gemini_thought_signatures' AND key IN (
       SELECT key FROM omniroute.key_value WHERE namespace='gemini_thought_signatures'
       ORDER BY CASE WHEN value IS JSON OBJECT THEN
         CASE WHEN jsonb_typeof(value::jsonb -> 'createdAt')='number'
           THEN (value::jsonb ->> 'createdAt')::numeric ELSE 0 END ELSE 0 END DESC,
         key COLLATE "C" ASC OFFSET 2000)`
    );
  });
}

export async function clearPersistedGeminiThoughtSignatures(): Promise<void> {
  const database = getSelectedPostgresDatabase();
  if (!database) return;
  await database.transaction(async (transaction) => {
    await transaction.query("SELECT pg_advisory_xact_lock(18765,15)");
    await transaction.query(
      `DELETE FROM omniroute.key_value WHERE namespace='gemini_thought_signatures'`
    );
  });
}
